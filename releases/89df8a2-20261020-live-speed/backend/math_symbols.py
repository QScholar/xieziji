def fence(char, size, height):
    """Return (width, paths), using fixed stroke thickness for any height."""
    if char == '.': return 0., []
    width = size * (.28 if char == '|' else .4 if char == '‖' else .48)
    l, r, mid = .08 * size, width-.08*size, width/2
    h = height
    if char in '()':
        p = [(r,0),(mid,h*.1),(l,h*.3),(l,h*.7),(mid,h*.9),(r,h)]
        if char == ')': p = [(width-x,y) for x,y in p]
        paths = [p]
    elif char in '[]⌊⌋⌈⌉':
        p = [(r,0),(l,0),(l,h),(r,h)]
        if char in '⌊⌋': p = p[1:]
        if char in '⌈⌉': p = p[:-1]
        if char in ']⌋⌉': p = [(width-x,y) for x,y in p]
        paths = [p]
    elif char in '{}':
        p = [(r,0),(mid,h*.05),(mid,h*.4),(l,h*.5),(mid,h*.6),(mid,h*.95),(r,h)]
        if char == '}': p = [(width-x,y) for x,y in p]
        paths = [p]
    elif char in '|‖':
        paths = [[(mid,0),(mid,h)]] if char == '|' else [[(l,0),(l,h)],[(r,0),(r,h)]]
    elif char in '<>⟨⟩':
        paths = [[(r,0),(l,h/2),(r,h)]]
        if char in '>⟩': paths = [[(width-x,y) for x,y in p] for p in paths]
    elif char in '/\\':
        paths = [[(r,0),(l,h)]] if char == '/' else [[(l,0),(r,h)]]
    else: raise ValueError('不支持的公式界定符：'+char)
    return width, paths
