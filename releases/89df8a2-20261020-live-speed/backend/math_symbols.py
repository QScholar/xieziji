def oval(cx, cy, rx, ry, start=0., stop=2 * math.pi, steps=24):
    return [(cx + rx * math.cos(start + (stop-start)*i/steps),
             cy + ry * math.sin(start + (stop-start)*i/steps)) for i in range(steps+1)]


